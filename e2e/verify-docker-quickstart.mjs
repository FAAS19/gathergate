// Verifies the 1-command Docker quickstart boots a working demo workspace in under 60 seconds.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";

const IMAGE = process.env.GATHERGATE_IMAGE || "gathergate:local";
const PORT = Number(process.env.DOCKER_TEST_PORT || 3097);
const LIMIT_MS = 60_000;
const suffix = `${Date.now()}-${Math.floor(Math.random() * 10_000)}`;
const containerName = `gathergate-qs-${suffix}`;
const volumeName = `gathergate_qs_${suffix}`;
const baseUrl = `http://127.0.0.1:${PORT}`;

function docker(args, opts = {}) {
  return execFileSync("docker", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts }).trim();
}

async function waitForHealth(deadlineMs) {
  while (Date.now() < deadlineMs) {
    try {
      const res = await fetch(`${baseUrl}/healthz`);
      if (res.ok) return await res.json();
    } catch {
      // Container still starting
    }
    await new Promise((r) => setTimeout(r, 250));
  }
  throw new Error(`Container did not pass /healthz within ${LIMIT_MS / 1000}s`);
}

const startedAt = Date.now();
const deadline = startedAt + LIMIT_MS;

try {
  docker([
    "run",
    "-d",
    "--name",
    containerName,
    "-p",
    `127.0.0.1:${PORT}:3080`,
    "-v",
    `${volumeName}:/data`,
    IMAGE,
  ]);

  const health = await waitForHealth(deadline);
  assert.equal(health.ok, true, "healthz ok must be true");

  const homeRes = await fetch(`${baseUrl}/`);
  assert.equal(homeRes.status, 200, "GET / must return 200");
  assert.match(homeRes.headers.get("content-type") || "", /text\/html/, "GET / must serve HTML");

  const setupRes = await fetch(`${baseUrl}/api/setup`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      workspaceName: "Quickstart Advisory",
      email: "ops@quickstart.test",
      password: "quickstart-password-123",
      loadDemo: true,
    }),
  });
  assert.equal(setupRes.status, 200, `POST /api/setup failed (${setupRes.status})`);

  const cookie = (setupRes.headers.getSetCookie?.()[0] || setupRes.headers.get("set-cookie") || "").split(";")[0];
  assert.ok(cookie, "POST /api/setup must set a session cookie");

  const [reqRes, sessionRes] = await Promise.all([
    fetch(`${baseUrl}/api/requests`, { headers: { cookie } }),
    fetch(`${baseUrl}/api/session`, { headers: { cookie } }),
  ]);
  assert.equal(reqRes.status, 200, "GET /api/requests must return 200");
  assert.equal(sessionRes.status, 200, "GET /api/session must return 200");

  const reqBody = await reqRes.json();
  const sessionBody = await sessionRes.json();
  assert.equal(reqBody.requests.length, 3, "Demo setup must seed 3 requests");
  assert.equal(sessionBody.readiness?.masterKeyAutoGenerated, true, "Zero-config boot must auto-generate MASTER_KEY");
  assert.equal(sessionBody.readiness?.hasDemoData, true, "Demo flag must be enabled");

  const elapsedMs = Date.now() - startedAt;
  assert.ok(elapsedMs < LIMIT_MS, `Cold start took ${elapsedMs}ms (limit ${LIMIT_MS}ms)`);
  console.log(`PASS: ${IMAGE} ready with 3 demo packs in ${(elapsedMs / 1000).toFixed(2)}s (< 60s)`);
} finally {
  try {
    docker(["rm", "-f", containerName]);
  } catch {
    // Ignore cleanup errors if container failed to start
  }
  try {
    docker(["volume", "rm", "-f", volumeName]);
  } catch {
    // Ignore volume cleanup errors
  }
}
