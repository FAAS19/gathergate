function jsonResponse(status: number, body: unknown) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json" },
  });
}

describe("DashboardPage", () => {
  it("rolls back optimistic bulk pause when server returns 500", async () => {
    const user = userEvent.setup();
    let resolveBulk!: (res: Response) => void;

    vi.spyOn(globalThis, "fetch").mockImplementation((input) => {
      const url = String(input);
      if (url === "/api/requests") {
        return Promise.resolve(jsonResponse(200, LIST_RESPONSE));
      }
      if (url === "/api/requests/bulk-reminders") {
        return new Promise<Response>((resolve) => {
          resolveBulk = resolve;
        });
      }
      return Promise.resolve(jsonResponse(404, { error: "Not mocked" }));
    });

    render(
      <TooltipProvider>
        <MemoryRouter>
          <DashboardPage
            session={SESSION}
            onSessionRefresh={vi.fn().mockResolvedValue(undefined)}
            theme="light"
            onToggleTheme={vi.fn()}
          />
        </MemoryRouter>
        <Toaster />
      </TooltipProvider>
    );

    await screen.findByText("Req Alpha");

    await user.click(screen.getByRole("checkbox", { name: "Select Req Alpha" }));
    await user.click(screen.getByRole("checkbox", { name: "Select Req Beta" }));
    expect(screen.getByText("2 selected")).toBeInTheDocument();

    await user.click(screen.getByRole("button", { name: "Pause reminders" }));
    // Optimistically shows Paused on both rows
    expect(screen.getAllByText("Paused")).toHaveLength(2);

    await act(async () => {
      resolveBulk(jsonResponse(500, { error: "Bulk update failed" }));
    });

    await waitFor(() => expect(screen.queryByText("Paused")).not.toBeInTheDocument());
    expect(await screen.findByText("Bulk update failed")).toBeInTheDocument();
  });

  it("renders persistent key setup banner only when masterKeyAutoGenerated is true", async () => {
    vi.spyOn(globalThis, "fetch").mockResolvedValue(jsonResponse(200, LIST_RESPONSE));

    const { rerender } = render(
      <TooltipProvider>
        <MemoryRouter>
          <DashboardPage
            session={{
              ...SESSION,
              readiness: { ...SESSION.readiness, masterKeyAutoGenerated: false },
            }}
            onSessionRefresh={vi.fn().mockResolvedValue(undefined)}
            theme="light"
            onToggleTheme={vi.fn()}
          />
        </MemoryRouter>
      </TooltipProvider>
    );

    await screen.findByText("Req Alpha");
    expect(screen.queryByText(/Encryption key stored beside data/i)).not.toBeInTheDocument();

    rerender(
      <TooltipProvider>
        <MemoryRouter>
          <DashboardPage
            session={{
              ...SESSION,
              readiness: { ...SESSION.readiness, masterKeyAutoGenerated: true },
            }}
            onSessionRefresh={vi.fn().mockResolvedValue(undefined)}
            theme="light"
            onToggleTheme={vi.fn()}
          />
        </MemoryRouter>
      </TooltipProvider>
    );

    expect(screen.getByText(/Encryption key stored beside data/i)).toBeInTheDocument();
    const link = screen.getByRole("link", { name: "View setup steps" });
    expect(link).toHaveAttribute("href", "/settings?section=instance");
  });
});
